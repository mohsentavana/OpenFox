//! The peer session: offer/answer, tracks, state machine. This is the
//! RFC 8829 signaling shape — the actual DTLS handshake for data channels
//! rides rustls in phase 2 (honest delta, docs/ARCHITECTURE.md).

use crate::RtcError;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PeerState {
    New,
    Checking,
    Connected,
    Disconnected,
    Failed,
    Closed,
}

impl PeerState {
    pub fn as_str(self) -> &'static str {
        match self {
            PeerState::New => "new",
            PeerState::Checking => "checking",
            PeerState::Connected => "connected",
            PeerState::Disconnected => "disconnected",
            PeerState::Failed => "failed",
            PeerState::Closed => "closed",
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TrackKind {
    Audio,
    Video,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TrackDirection {
    SendRecv,
    SendOnly,
    RecvOnly,
    Inactive,
}

#[derive(Debug, Clone)]
pub struct Track {
    pub kind: TrackKind,
    pub direction: TrackDirection,
    pub mid: String,
    pub ssrc: u32,
}

#[derive(Debug, Clone)]
pub struct LocalDescription {
    pub sdp: crate::sdp::SessionDescription,
    pub kind: DescriptionKind,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum DescriptionKind {
    Offer,
    Answer,
}

pub struct PeerSession {
    state: PeerState,
    tracks: Vec<Track>,
    local: Option<LocalDescription>,
    remote: Option<crate::sdp::SessionDescription>,
    dtls_fingerprint: String,
    consent_misses: u8,
}

impl PeerSession {
    pub fn new() -> Self {
        PeerSession {
            state: PeerState::New,
            tracks: Vec::new(),
            local: None,
            remote: None,
            // SHA-256 of our self-signed DTLS certificate. Generated by
            // the TLS layer; pinned here for SDP.
            dtls_fingerprint: "00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00".into(),
            consent_misses: 0,
        }
    }

    pub fn state(&self) -> PeerState {
        self.state
    }

    pub fn tracks(&self) -> &[Track] {
        &self.tracks
    }

    pub fn add_track(&mut self, track: Track) {
        self.tracks.retain(|existing| existing.mid != track.mid);
        self.tracks.push(track);
    }

    /// Create an offer covering every registered track.
    pub fn create_offer(&mut self) -> Result<LocalDescription, RtcError> {
        if self.state == PeerState::Closed {
            return Err(RtcError::WrongState(self.state.as_str().into()));
        }
        let sdp = crate::sdp::SessionDescription::for_offer(&self.tracks, &self.dtls_fingerprint);
        self.local = Some(LocalDescription {
            sdp: sdp.clone(),
            kind: DescriptionKind::Offer,
        });
        self.state = PeerState::Checking;
        Ok(self.local.clone().expect("just set"))
    }

    /// Answer a remote offer, aligning directions per track.
    pub fn create_answer(
        &mut self,
        remote: crate::sdp::SessionDescription,
    ) -> Result<LocalDescription, RtcError> {
        if self.state == PeerState::Closed {
            return Err(RtcError::WrongState(self.state.as_str().into()));
        }
        self.remote = Some(remote.clone());
        let sdp = crate::sdp::SessionDescription::for_answer(&self.tracks, &self.dtls_fingerprint);
        self.local = Some(LocalDescription {
            sdp,
            kind: DescriptionKind::Answer,
        });
        self.state = PeerState::Checking;
        Ok(self.local.clone().expect("just set"))
    }

    pub fn set_remote_description(&mut self, remote: crate::sdp::SessionDescription) -> Result<(), RtcError> {
        self.remote = Some(remote);
        self.state = PeerState::Checking;
        Ok(())
    }

    /// ICE-level connectivity news drives the session state; consent
    /// freshness keeps it honest.
    pub fn on_connectivity(&mut self, connected: bool) {
        self.state = match (self.state, connected) {
            (PeerState::Checking | PeerState::Disconnected, true) => PeerState::Connected,
            (PeerState::Connected, false) => {
                self.consent_misses += 1;
                // One missed keepalive is a hiccup; three is a problem.
                if self.consent_misses >= 3 {
                    self.consent_misses = 0;
                    PeerState::Disconnected
                } else {
                    PeerState::Connected
                }
            }
            (state, _) => state,
        };
    }

    pub fn close(&mut self) {
        self.state = PeerState::Closed;
    }
}

impl Default for PeerSession {
    fn default() -> Self {
        Self::new()
    }
}
